CREATE TABLE app_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(160) NOT NULL UNIQUE, display_name VARCHAR(100) NOT NULL,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL CHECK(role IN ('STAFF','STUDENT'))
);
CREATE TABLE assets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL,
 category VARCHAR(60) NOT NULL, location VARCHAR(80) NOT NULL,
 description VARCHAR(800) NOT NULL, state VARCHAR(20) NOT NULL CHECK(state IN ('AVAILABLE','MAINTENANCE'))
);
CREATE TABLE loans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id), user_id BIGINT NOT NULL REFERENCES app_users(id),
 start_on DATE NOT NULL, due_on DATE NOT NULL, purpose VARCHAR(500) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('PENDING','APPROVED','CHECKED_OUT','RETURNED','REJECTED','CANCELLED')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 return_note VARCHAR(500), CHECK(due_on >= start_on)
);
CREATE INDEX loan_asset_schedule ON loans(asset_id, status, start_on, due_on);
CREATE INDEX loan_owner ON loans(user_id);
CREATE TABLE issues (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id), reporter_id BIGINT NOT NULL REFERENCES app_users(id),
 description VARCHAR(1000) NOT NULL, status VARCHAR(20) NOT NULL CHECK(status IN ('OPEN','RESOLVED')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, resolved_at TIMESTAMP WITH TIME ZONE, resolution VARCHAR(1000)
);
CREATE TABLE audit_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor_id BIGINT NOT NULL REFERENCES app_users(id), action VARCHAR(50) NOT NULL,
 target VARCHAR(100) NOT NULL, detail VARCHAR(1000) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
